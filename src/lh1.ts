/** 辞書 (リングバッファ) のサイズ。 */
const N = 4096;
/** 最長一致長。 */
const F = 60;
/** 一致とみなす最小長 - 1。符号語 256 以降が一致を表す。 */
const THRESHOLD = 2;
/** シンボル数。リテラル 256 種 + 一致長 (F - THRESHOLD + 1) 種。 */
const N_CHAR = 256 - THRESHOLD + F;
/** 木の節点数。 */
const T = N_CHAR * 2 - 1;
/** 根の位置。 */
const ROOT = T - 1;
/** この頻度に達したら木を再構築して全体を半減させる。 */
const MAX_FREQ = 0x8000;

