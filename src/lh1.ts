/**
 * 適応的ハフマン木。
 *
 * 節点は頻度の昇順に並んだ 1 本の配列 `freq` として保持し、`son` が子への
 * 参照、`prnt` が親への参照を持つ。葉は `son[i] >= T` で表し、そのときの
 * `son[i] - T` がシンボル番号になる。
 *
 * 1 シンボル復号するたびに {@link update} を呼び、頻度を 1 増やしつつ
 * 昇順が崩れたら節点を入れ替える。これにより符号長が動的に変化する。
 */
class AdaptiveHuffmanTree {
  private readonly freq = new Uint16Array(T + 1);
  private readonly prnt = new Uint16Array(T + N_CHAR);
  private readonly son = new Uint16Array(T);

  constructor() {
    // 葉をすべて頻度 1 で作る
    for (let i = 0; i < N_CHAR; i++) {
      this.freq[i] = 1;
      this.son[i] = i + T;
      this.prnt[i + T] = i;
    }
    // 隣り合う 2 節点を束ねて内部節点を作っていく
    let i = 0;
    let j = N_CHAR;
    while (j <= ROOT) {
      this.freq[j] = this.freq[i] + this.freq[i + 1];
      this.son[j] = i;
      this.prnt[i] = j;
      this.prnt[i + 1] = j;
      i += 2;
      j++;
    }
    // 番兵。update の昇順探索がここで必ず止まる
    this.freq[T] = 0xffff;
    this.prnt[ROOT] = 0;
  }

  /** 木を辿って 1 シンボル復号し、木を更新する。 */
  decodeSymbol(reader: BitReader): number {
    let c = this.son[ROOT];
    // 根から葉まで、読んだビットで子を選びながら降りる
    while (c < T) {
      c += reader.read(1);
      c = this.son[c];
    }
    c -= T;
    this.update(c);
    return c;
  }

  /** 頻度が上限に達したので、全体を半減させて木を組み直す。 */
  private reconstruct(): void {
    const { freq, son, prnt } = this;

    // 葉を配列前半に集め、頻度を切り上げ半減する
    let j = 0;
    for (let i = 0; i < T; i++) {
      if (son[i] >= T) {
        freq[j] = (freq[i] + 1) >>> 1;
        son[j] = son[i];
        j++;
      }
    }

    // 子を束ねながら、頻度の昇順を保つ位置に挿入していく
    for (let i = 0, k = N_CHAR; k < T; i += 2, k++) {
      const f = freq[i] + freq[i + 1];
      freq[k] = f;
      let m = k - 1;
      while (f < freq[m]) m--;
      m++;
      // freq[m..k-1] と son[m..k-1] を 1 つ後ろへずらして m 番目に挿入する
      for (let p = k; p > m; p--) {
        freq[p] = freq[p - 1];
        son[p] = son[p - 1];
      }
      freq[m] = f;
      son[m] = i;
    }

    // 親を張り直す
    for (let i = 0; i < T; i++) {
      const k = son[i];
      if (k >= T) {
        prnt[k] = i;
      } else {
        prnt[k] = i;
        prnt[k + 1] = i;
      }
    }
  }

  /** シンボル `sym` の頻度を 1 増やし、崩れた昇順を修復する。 */
  private update(sym: number): void {
    const { freq, son, prnt } = this;

    if (freq[ROOT] === MAX_FREQ) {
      this.reconstruct();
    }

    let c = prnt[sym + T];
    do {
      const k = ++freq[c];

      // 昇順が崩れたら、同じ頻度の並びの末尾と入れ替える
      let l = c + 1;
      if (k > freq[l]) {
        while (k > freq[++l]);
        l--;

        freq[c] = freq[l];
        freq[l] = k;

        const i = son[c];
        prnt[i] = l;
        if (i < T) prnt[i + 1] = l;

        const j = son[l];
        son[l] = i;

        prnt[j] = c;
        if (j < T) prnt[j + 1] = c;
        son[c] = j;

        c = l;
      }
      c = prnt[c];
    } while (c !== 0); // 根まで遡る
  }
}

/**
 * 一致位置を復号する。
 *
 * 上位 6 ビットを固定接頭符号で引き、下位 6 ビットをそのまま読む。
 *
 * @param reader - ビットリーダー
 * @returns 0 以上 {@link N} 未満の位置
 */
function decodePosition(reader: BitReader): number {
  // 8 ビット先読みして表を引く。消費するのは符号長ぶんだけ
  let i = reader.read(8);
  const high = D_CODE[i] << 6;

  // 下位ビットの残りを継ぎ足す。read(n) は MSB 先頭で n ビット返すため、
  // 「1 ビットずつ読んで左シフト」の反復と厳密に等価で、呼び出しは 1 回で済む
  const remaining = D_LEN[i] - 2;
  if (remaining > 0) {
    i = ((i << remaining) | reader.read(remaining)) & 0xffff;
  }
  return high | (i & 0x3f);
}

/**
 * `-lh1-` 形式の圧縮データを展開する。
 *
 * @param compressedData - アーカイブ全体のバイト列
 * @param offset - 圧縮データの開始オフセット
 * @param originalSize - 展開後のサイズ (ヘッダーの値)
 * @returns 展開されたバイト列
 * @throws originalSize が上限を超える場合は Error
 */
export function decodeLh1(
  compressedData: Uint8Array,
  offset: number,
  originalSize: number,
  end?: number
): Uint8Array {
  if (originalSize > MAX_ORIGINAL_SIZE) {
    throw new LhaLimitError(
      `展開後サイズが上限 (${MAX_ORIGINAL_SIZE} bytes) を超えています: ${originalSize} bytes`
    );
  }
  if (originalSize === 0) return new Uint8Array(0);

  const out = new Uint8Array(originalSize);
  const reader = new BitReader(compressedData, offset, end);
  const tree = new AdaptiveHuffmanTree();

  // 辞書は空白で初期化し、書き込み位置は N - F から始める。
  // (この初期状態が一致することがビットストリーム互換の前提になる)
  const dict = new Uint8Array(N).fill(0x20);
  let dictPos = N - F;
  let outPos = 0;

  while (outPos < originalSize) {
    // 入力を使い切っているのに出力が足りない = 書庫が途中で切れている。
    // BitReader は末尾を過ぎても 0 を返し続けるため、この検査が無いと
    // 壊れた書庫からそれらしいデータを黙って返してしまう。
    if (reader.exhausted) {
      throwTruncated(outPos, originalSize);
    }

    const c = tree.decodeSymbol(reader);

    if (c < 256) {
      out[outPos++] = c;
      dict[dictPos] = c;
      dictPos = (dictPos + 1) & (N - 1);
      continue;
    }

    // 256 以降は一致。符号語から長さを復元する
    const length = c - 256 + THRESHOLD + 1;
    let srcPos = (dictPos - decodePosition(reader) - 1) & (N - 1);
    for (let k = 0; k < length && outPos < originalSize; k++) {
      const b = dict[srcPos];
      out[outPos++] = b;
      dict[dictPos] = b;
      dictPos = (dictPos + 1) & (N - 1);
      srcPos = (srcPos + 1) & (N - 1);
    }
  }

  return out;
}
