/**
 * `-lh1-` 展開モジュール。
 *
 * `-lh1-` は LHarc 1.x 世代の方式で、LZSS (4KB 辞書・最長一致 60) の上に
 * **適応的ハフマン符号**を載せたものである。ブロックごとに静的ハフマン表を
 * 送る `-lh4-`〜`-lh7-` とはまったく別の仕組みで、シンボルを 1 つ復号する
 * たびに木を更新していく。
 *
 * ## 出典
 *
 * 本実装は吉崎栄泰氏の `lzhuf.c` (1988-11-20、コメント英訳 奥村晴彦氏 1989-04-07)
 * が定義するアルゴリズムに基づく。`-lh1-` は LHarc の作者自身による lzhuf を
 * 起源としており、パラメータも一致する:
 *
 * | 定数 | 値 | 根拠 |
 * |---|---|---|
 * | 辞書サイズ | 4096 (dicbit=12) | `Hacking_of_LHa` の方式表 |
 * | 最長一致長 | 60 | 同上 |
 * | THRESHOLD | 2 | lzhuf。シンボル数 314 = 256 - 2 + 60 と整合 |
 *
 * `lzhuf.c` は自由な使用・配布・改変が認められている。詳細は NOTICE.md を参照。
 * LHa for UNIX の `dhuf.c` は OSI ライセンスではないため参照していない。
 *
 * ## 位置符号
 *
 * 一致位置の上位 6 ビットは固定の接頭符号で、下位 6 ビットはそのまま送られる。
 * 固定符号は {@link D_CODE} / {@link D_LEN} の 2 表で、8 ビット先読みして
 * 引く形になっている。この 2 表は 64 シンボルの完全な接頭符号を成す
 * (Kraft 和 = 1.0 を検証済み)。
 *
 * @module
 */

